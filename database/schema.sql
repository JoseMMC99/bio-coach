-- ==============================================================================
-- BioCoach AI: PostgreSQL Schema on Supabase
-- Automated Health, Performance and Nutrition System
-- ==============================================================================

-- 1. TABLE: Daily Recovery and Sleep Architecture Metrics
CREATE TABLE IF NOT EXISTS daily_recovery (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    recorded_date DATE NOT NULL,
    sleep_hours NUMERIC(4,2),
    deep_sleep_hours NUMERIC(4,2),
    rem_sleep_hours NUMERIC(4,2),
    respiratory_rate NUMERIC(4,2),
    wrist_temp_deviation NUMERIC(4,2),
    resting_hr NUMERIC(5,2),
    hrv_ms NUMERIC(5,2),
    daylight_minutes INT,
    recovery_score INT, -- Normalized score (0 to 100)
    gemini_verdict TEXT,
    athlete_id TEXT DEFAULT 'public_demo',
    is_demo BOOLEAN DEFAULT false,
    CONSTRAINT unique_athlete_date UNIQUE (athlete_id, recorded_date)
);

-- 2. TABLE: Workout Sessions and Cardiovascular Load
CREATE TABLE IF NOT EXISTS workouts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    workout_type TEXT NOT NULL,
    duration_minutes NUMERIC(5,2),
    active_calories INT,
    avg_hr INT,
    max_hr INT,
    recovery_hr_1min INT,
    gemini_feedback TEXT,
    athlete_id TEXT DEFAULT 'public_demo',
    is_demo BOOLEAN DEFAULT false
);

-- 3. TABLE: Nutrition and Meal Logging
CREATE TABLE IF NOT EXISTS nutrition_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    logged_date DATE DEFAULT CURRENT_DATE,
    meal_type TEXT, -- 'desayuno', 'almuerzo', 'cena', 'snack'
    raw_text TEXT NOT NULL,
    estimated_calories INT,
    protein_g NUMERIC(5,2),
    carbs_g NUMERIC(5,2),
    fat_g NUMERIC(5,2),
    athlete_id TEXT DEFAULT 'public_demo',
    is_demo BOOLEAN DEFAULT false
);

-- 4. TABLE: Instant Heart Rate and Stress On-Demand Checks
CREATE TABLE IF NOT EXISTS hr_checkins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    current_hr INT NOT NULL,
    stress_level INT, -- Estimated biological stress (0 to 100)
    user_sensation TEXT, -- 'palpitaciones', 'ansiedad', 'rutina', 'estrés'
    gemini_guidance TEXT,
    athlete_id TEXT DEFAULT 'public_demo',
    is_demo BOOLEAN DEFAULT false
);

-- ==============================================================================
-- SECURITY: Row Level Security (RLS) & Privacy Isolation
-- ==============================================================================
ALTER TABLE daily_recovery ENABLE ROW LEVEL SECURITY;
ALTER TABLE workouts ENABLE ROW LEVEL SECURITY;
ALTER TABLE nutrition_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE hr_checkins ENABLE ROW LEVEL SECURITY;

-- Public Demo: Anyone without athlete token only views records marked is_demo = true
CREATE POLICY "Public Read Demo Only daily_recovery" ON daily_recovery FOR SELECT USING (is_demo = true);
CREATE POLICY "Public Read Demo Only workouts" ON workouts FOR SELECT USING (is_demo = true);
CREATE POLICY "Public Read Demo Only nutrition_logs" ON nutrition_logs FOR SELECT USING (is_demo = true);
CREATE POLICY "Public Read Demo Only hr_checkins" ON hr_checkins FOR SELECT USING (is_demo = true);

-- Private Athlete: Only the authorized athlete can query their private health records
CREATE POLICY "Private Athlete Select daily_recovery" ON daily_recovery FOR SELECT 
USING (is_demo = true OR athlete_id = current_setting('request.headers', true)::json->>'x-athlete-token');

CREATE POLICY "Private Athlete Insert daily_recovery" ON daily_recovery FOR INSERT 
WITH CHECK (true);

CREATE POLICY "Private Athlete Select workouts" ON workouts FOR SELECT 
USING (is_demo = true OR athlete_id = current_setting('request.headers', true)::json->>'x-athlete-token');

CREATE POLICY "Private Athlete Insert workouts" ON workouts FOR INSERT 
WITH CHECK (true);
